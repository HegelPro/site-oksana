export const publishedCourses = courses.filter((course) => !course.draft).sort((a, b) => a.number.localeCompare(b.number));

export function getCoursePricing(course: Course, now = new Date()) {
  const earlyActive = Boolean(course.earlyOffer && now.getTime() <= Date.parse(course.earlyOffer.until));
  return { earlyActive, current: earlyActive ? course.earlyOffer!.price : course.price };
}

export function getCourse(slug: string): Course | undefined {
  return courses.find((course) => course.slug === slug);
}
